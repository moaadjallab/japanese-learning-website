/**
 * Brand & business configuration — the ONLY place the brand name and contact details live.
 * Replace every value marked PLACEHOLDER before launch (see PLACEHOLDERS.md).
 */
import type { Locale } from '@/i18n/config';

export interface SiteConfig {
  /** Brand name per locale. The brand must stay independent of any single teacher's name. */
  name: Record<Locale, string>;
  /** Short tagline shown in the footer and used in metadata. */
  tagline: Record<Locale, string>;
  /** Decorative Japanese wordmark accent (日本語 = "Japanese language"). */
  japaneseAccent: string;
  /** Path to the logo mark. The inline SVG version lives in src/components/layout/LogoMark.astro. */
  logo: string;
  contact: {
    /** General enquiries address shown publicly. */
    email: string;
    /** International format, digits only (used for wa.me links). */
    whatsapp: string;
    /** Human-readable WhatsApp number shown on the page. */
    whatsappDisplay: string;
    instagramHandle: string;
    instagramUrl: string;
  };
  legal: {
    /** Registered legal entity name. */
    entityName: string;
    /** Registered address / country of incorporation. */
    address: string;
    /** Company registration number (e.g. RC / ICE in Morocco). */
    registrationNumber: string;
    /** Email for privacy / data requests. */
    privacyEmail: string;
  };
  /** Default social preview image (1200×630). */
  ogImage: string;
  /** Twitter / X handle without @ (optional). */
  twitterHandle?: string;
}

